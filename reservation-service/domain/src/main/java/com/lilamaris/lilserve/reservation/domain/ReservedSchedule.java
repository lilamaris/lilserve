package com.lilamaris.lilserve.reservation.domain;

import com.lilamaris.lilserve.kernel.condition.TimePrecondition;
import com.lilamaris.lilserve.reservation.domain.converter.IsoDayOfWeekConverter;
import com.lilamaris.lilserve.reservation.domain.id.ReservationId;
import com.lilamaris.lilserve.reservation.domain.id.ReservedScheduleId;
import com.lilamaris.lilserve.reservation.domain.id.RoomId;
import com.lilamaris.lilserve.reservation.domain.id.ScheduleId;
import com.lilamaris.lilserve.reservation.domain.id.SeatId;
import jakarta.persistence.AttributeOverride;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Embedded;
import jakarta.persistence.EmbeddedId;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import java.time.DayOfWeek;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.time.ZoneId;
import java.util.Objects;
import java.util.UUID;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

/**
 * A dated seat allocation: one seat's usage of one slot on one service date. Each row carries the
 * copied local times of the original slot, the service date, and the timezone, so the occupied
 * absolute instants are derived from the writer's snapshot instead of re-read from the slot. The
 * {@code startsAt}, {@code endsAt}, and {@code dayOfWeek} values are generated by the database and
 * are read-only in this mapping.
 */
@Entity
@Table(name = "reserved_schedule")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class ReservedSchedule {
    @EmbeddedId private ReservedScheduleId id;

    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "reservation_id", nullable = false))
    private ReservationId reservationId;

    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "room_id", nullable = false))
    private RoomId roomId;

    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "seat_id", nullable = false))
    private SeatId seatId;

    @Embedded
    @AttributeOverride(name = "value", column = @Column(name = "schedule_id", nullable = false))
    private ScheduleId scheduleId;

    @Column(name = "start_at", nullable = false)
    private LocalTime startAt;

    @Column(name = "end_at", nullable = false)
    private LocalTime endAt;

    @Column(name = "reservation_date", nullable = false)
    private LocalDate reservationDate;

    @Column(name = "time_zone", nullable = false)
    private String timeZone;

    @Column(name = "starts_at", insertable = false, updatable = false, nullable = false)
    private Instant startsAt;

    @Column(name = "ends_at", insertable = false, updatable = false, nullable = false)
    private Instant endsAt;

    @Convert(converter = IsoDayOfWeekConverter.class)
    @Column(name = "day_of_week", insertable = false, updatable = false, nullable = false)
    private DayOfWeek dayOfWeek;

    @Column(name = "created_at", updatable = false, nullable = false)
    private Instant createdAt;

    @Column(name = "deleted_at")
    private Instant deletedAt;

    private ReservedSchedule(
            ReservedScheduleId id,
            ReservationId reservationId,
            RoomId roomId,
            SeatId seatId,
            ScheduleId scheduleId,
            LocalTime startAt,
            LocalTime endAt,
            LocalDate reservationDate,
            String timeZone,
            Instant createdAt) {
        this.id = Objects.requireNonNull(id, "id must not be null.");
        this.reservationId =
                Objects.requireNonNull(reservationId, "reservationId must not be null.");
        this.roomId = Objects.requireNonNull(roomId, "roomId must not be null.");
        this.seatId = Objects.requireNonNull(seatId, "seatId must not be null.");
        this.scheduleId = Objects.requireNonNull(scheduleId, "scheduleId must not be null.");
        this.startAt = Objects.requireNonNull(startAt, "startAt must not be null.");
        this.endAt = Objects.requireNonNull(endAt, "endAt must not be null.");
        this.reservationDate =
                Objects.requireNonNull(reservationDate, "reservationDate must not be null.");
        this.timeZone = ZoneId.of(timeZone).getId();
        this.createdAt = Objects.requireNonNull(createdAt, "createdAt must not be null.");
        TimePrecondition.requireAfter(endAt, startAt);
    }

    /**
     * Creates a dated seat allocation from a slot. The scope columns must match the reservation
     * header, and the slot must belong to the same room and repeat on the service date's weekday;
     * the database enforces that consistency.
     *
     * @param id the allocation identifier
     * @param reservationId the reservation header this allocation belongs to
     * @param roomId the room of the seat and the slot
     * @param seatId the reserved seat
     * @param scheduleId the original slot used to create this allocation
     * @param startAt the copied local start time of the slot
     * @param endAt the copied local end time of the slot, strictly after {@code startAt}
     * @param reservationDate the service date
     * @param timeZone the timezone copied from the reservation header, for example {@code
     *     Asia/Seoul}
     * @param createdAt the creation time
     * @return the allocation
     * @throws NullPointerException if any argument is null
     * @throws com.lilamaris.lilserve.kernel.exception.IllegalComparisonConditionException if {@code
     *     endAt} is not after {@code startAt}
     * @throws java.time.DateTimeException if {@code timeZone} is not a valid timezone
     */
    public static ReservedSchedule of(
            UUID id,
            UUID reservationId,
            UUID roomId,
            UUID seatId,
            UUID scheduleId,
            LocalTime startAt,
            LocalTime endAt,
            LocalDate reservationDate,
            String timeZone,
            Instant createdAt) {
        return new ReservedSchedule(
                ReservedScheduleId.of(id),
                ReservationId.of(reservationId),
                RoomId.of(roomId),
                SeatId.of(seatId),
                ScheduleId.of(scheduleId),
                startAt,
                endAt,
                reservationDate,
                timeZone,
                createdAt);
    }

    /**
     * Cancels this allocation. The reservation header must be cancelled in the same transaction;
     * the reservation workflow must cancel all allocations together rather than expose partial
     * cancellation.
     *
     * @param deletedAt the cancellation time, at or after {@code createdAt}
     * @throws NullPointerException if {@code deletedAt} is null
     * @throws com.lilamaris.lilserve.kernel.exception.IllegalComparisonConditionException if {@code
     *     deletedAt} is before {@code createdAt}
     * @throws IllegalStateException if the allocation is already cancelled
     */
    public void delete(Instant deletedAt) {
        validateNotDeleted();
        TimePrecondition.requireAfterOrEqual(deletedAt, createdAt);
        this.deletedAt = deletedAt;
    }

    /**
     * Checks whether the allocation has been cancelled.
     *
     * @return true if the allocation has a deletion time
     */
    public boolean isDeleted() {
        return deletedAt != null;
    }

    /**
     * Requires that the allocation is still active.
     *
     * @throws IllegalStateException if the allocation has been cancelled
     */
    public void validateNotDeleted() {
        if (isDeleted()) {
            throw new IllegalStateException("Deleted reserved schedule cannot be used.");
        }
    }

    /**
     * Requires that the allocation has been cancelled.
     *
     * @throws IllegalStateException if the allocation is still active
     */
    public void validateDeleted() {
        if (!isDeleted()) {
            throw new IllegalStateException("Not deleted reserved schedule cannot be used.");
        }
    }

    /**
     * Returns the start of the occupied interval, computed from the stored service date, local
     * start time, and timezone. The value is available before the row is inserted, unlike {@code
     * getStartsAt()}, which the database fills on insert.
     *
     * @return the inclusive start instant
     */
    public Instant startInstant() {
        return LocalDateTime.of(reservationDate, startAt).atZone(zone()).toInstant();
    }

    /**
     * Returns the end of the occupied interval, computed from the stored service date, local end
     * time, and timezone. The interval is half-open, so the end instant is not occupied.
     *
     * @return the exclusive end instant
     */
    public Instant endInstant() {
        return LocalDateTime.of(reservationDate, endAt).atZone(zone()).toInstant();
    }

    /**
     * Checks whether this allocation occupies part of the given interval. Intervals are half-open,
     * so an interval starting exactly at this allocation's end does not overlap.
     *
     * @param otherStart the inclusive start of the other interval
     * @param otherEnd the exclusive end of the other interval
     * @return true if the intervals share occupied time
     * @throws NullPointerException if either bound is null
     */
    public boolean overlaps(Instant otherStart, Instant otherEnd) {
        Objects.requireNonNull(otherStart, "otherStart must not be null.");
        Objects.requireNonNull(otherEnd, "otherEnd must not be null.");
        return startInstant().isBefore(otherEnd) && otherStart.isBefore(endInstant());
    }

    /**
     * Checks whether this allocation occupies the same seat over the same interval as another
     * allocation.
     *
     * @param other the allocation to compare
     * @return true if both allocations are for the same seat and their intervals overlap
     * @throws NullPointerException if {@code other} is null
     */
    public boolean overlaps(ReservedSchedule other) {
        Objects.requireNonNull(other, "other must not be null.");
        return seatId.equals(other.seatId) && overlaps(other.startInstant(), other.endInstant());
    }

    private ZoneId zone() {
        return ZoneId.of(timeZone);
    }
}
